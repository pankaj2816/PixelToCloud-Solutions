class I18nManager {
  constructor() {
    this.currentLang = 'en';
    const stored = localStorage.getItem('p2c_lang');
    if (stored && I18N_DICTIONARY[stored]) {
      this.currentLang = stored;
    }
    this.selector = document.getElementById('language-selector');
    this.init();
  }

  init() {
    this.populateLanguageSelectors();
    this.applyLanguage(this.currentLang, false);

    // Bind event listener to all language selector dropdowns
    document.querySelectorAll('.lang-select, #language-selector, #mobile-language-selector').forEach(sel => {
      sel.addEventListener('change', (e) => {
        const selected = e.target.value;
        if (selected && I18N_DICTIONARY[selected]) {
          this.applyLanguage(selected, true);
        }
      });
    });
  }

  populateLanguageSelectors() {
    const options = [
      { code: 'en', label: 'EN (English)' },
      { code: 'hi', label: 'HI (हिन्दी)' },
      { code: 'fr', label: 'FR (Français)' },
      { code: 'ru', label: 'RU (Русский)' },
      { code: 'de', label: 'DE (Deutsch)' },
      { code: 'es', label: 'ES (Español)' },
      { code: 'ja', label: 'JA (日本語)' },
      { code: 'ar', label: 'AR (العربية)' }
    ];

    document.querySelectorAll('.lang-select, #language-selector, #mobile-language-selector').forEach(sel => {
      sel.innerHTML = options.map(opt => `<option value="${opt.code}" ${opt.code === this.currentLang ? 'selected' : ''}>${opt.label}</option>`).join('');
    });
  }

  applyLanguage(lang, showToast = true) {
    if (!I18N_DICTIONARY[lang]) lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('p2c_lang', lang);

    // Synchronize all dropdown selectors
    document.querySelectorAll('.lang-select, #language-selector, #mobile-language-selector').forEach(sel => {
      sel.value = lang;
    });

    // Support RTL direction for Arabic
    if (lang === 'ar') {
      document.documentElement.setAttribute('dir', 'rtl');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
    }

    // Translate all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(elem => {
      const key = elem.getAttribute('data-i18n');
      const translation = I18N_DICTIONARY[lang]?.[key] || I18N_DICTIONARY['en']?.[key];
      if (translation) {
        elem.textContent = translation;
      }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(elem => {
      const key = elem.getAttribute('data-i18n-placeholder');
      const translation = I18N_DICTIONARY[lang]?.[key] || I18N_DICTIONARY['en']?.[key];
      if (translation) {
        elem.setAttribute('placeholder', translation);
      }
    });

    if (showToast && window.showToast) {
      const langNames = {
        en: "English",
        hi: "हिन्दी (Hindi)",
        fr: "Français (French)",
        ru: "Русский (Russian)",
        de: "Deutsch (German)",
        es: "Español (Spanish)",
        ja: "日本語 (Japanese)",
        ar: "العربية (Arabic)"
      };
      window.showToast(`🌐 Switched to ${langNames[lang] || lang} · More Languages Coming Soon!`);
    }
  }
}

document.addEventListener('DOMContentLoaded', () => {
  window.i18nInstance = new I18nManager();
});

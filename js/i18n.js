class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('p2c_lang') || 'en';
    this.selector = document.getElementById('language-selector');
    this.init();
  }

  init() {
    this.applyLanguage(this.currentLang);
    if (this.selector) {
      this.selector.value = this.currentLang;
      this.selector.addEventListener('change', (e) => {
        this.applyLanguage(e.target.value);
      });
    }

    const mobileSelector = document.getElementById('mobile-language-selector');
    if (mobileSelector) {
      mobileSelector.value = this.currentLang;
      mobileSelector.addEventListener('change', (e) => {
        this.applyLanguage(e.target.value);
      });
    }
  }

  applyLanguage(lang) {
    if (!I18N_DICTIONARY[lang]) lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('p2c_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(elem => {
      const key = elem.getAttribute('data-i18n');
      if (I18N_DICTIONARY[lang][key]) {
        elem.textContent = I18N_DICTIONARY[lang][key];
      }
    });

    if (window.App) {
      const langNames = { en: "English", hi: "हिन्दी (Hindi)", fr: "Français", de: "Deutsch", ru: "Русский" };
      window.App.showToast(`🌐 Language switched to ${langNames[lang] || lang}`);
    }
  }
}

document.addEventListener('DOMContentLoaded', () => {
  window.i18nInstance = new I18nManager();
});
